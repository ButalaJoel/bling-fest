import { env } from "./env.js";
import { v2 as cloudinary } from "cloudinary";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { randomUUID } from "node:crypto";

// Application photos are PRIVATE. In Cloudinary they're uploaded as "authenticated" assets
// (no public URL exists); admins get a download link that expires after 5 minutes.
// Local disk storage is a development fallback only and is refused in production.

const configured = Boolean(env("CLOUDINARY_CLOUD_NAME") && env("CLOUDINARY_API_KEY") && env("CLOUDINARY_API_SECRET"));
if (configured) {
  cloudinary.config({
    cloud_name: env("CLOUDINARY_CLOUD_NAME"),
    api_key: env("CLOUDINARY_API_KEY"),
    api_secret: env("CLOUDINARY_API_SECRET"),
    secure: true,
  });
}

export const storageMode: "cloudinary" | "local" | "none" =
  configured ? "cloudinary" : env("NODE_ENV") === "production" ? "none" : "local";

const LOCAL_DIR = path.resolve(process.cwd(), ".uploads");
const EXT: Record<string, string> = { "image/jpeg": "jpg", "image/png": "png", "image/webp": "webp" };

export async function savePhoto(applicationId: string, buffer: Buffer, mime: string): Promise<{ storage: "cloudinary" | "local"; key: string }> {
  if (storageMode === "cloudinary") {
    const key = await new Promise<string>((resolve, reject) => {
      cloudinary.uploader.upload_stream(
        { folder: `bling-fest/applications/${applicationId}`, public_id: randomUUID(), resource_type: "image", type: "authenticated", overwrite: false },
        (error, result) => (error || !result ? reject(error ?? new Error("upload failed")) : resolve(result.public_id)),
      ).end(buffer);
    });
    return { storage: "cloudinary", key };
  }
  if (storageMode === "local") {
    const key = `${applicationId}/${randomUUID()}.${EXT[mime]}`;
    await mkdir(path.join(LOCAL_DIR, applicationId), { recursive: true });
    await writeFile(path.join(LOCAL_DIR, key), buffer, { flag: "wx" });
    return { storage: "local", key };
  }
  throw new Error("STORAGE_NOT_CONFIGURED");
}

/** Short-lived link for an admin to view a private photo. */
export function signedPhotoUrl(key: string, mime: string): string {
  return cloudinary.utils.private_download_url(key, EXT[mime], {
    type: "authenticated",
    resource_type: "image",
    expires_at: Math.floor(Date.now() / 1000) + 300,
  });
}

export async function readLocalPhoto(key: string): Promise<Buffer> {
  // Keys are generated by us (uuid/uuid.ext); re-check to rule out path traversal.
  if (!/^[0-9a-f-]{36}\/[0-9a-f-]{36}\.(jpg|png|webp)$/.test(key)) throw new Error("bad key");
  return readFile(path.join(LOCAL_DIR, key));
}

export async function deleteCloudinaryPhotos(keys: string[]) {
  if (storageMode !== "cloudinary" || !keys.length) return;
  await cloudinary.api.delete_resources(keys, { type: "authenticated", resource_type: "image" }).catch((e) => console.error("Photo delete failed:", e));
}

/** Check the real file type from its first bytes — the browser's claimed type can be faked. */
export function sniffImage(buf: Buffer): "image/jpeg" | "image/png" | "image/webp" | null {
  if (buf.length >= 3 && buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return "image/jpeg";
  if (buf.length >= 8 && buf.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) return "image/png";
  if (buf.length >= 12 && buf.toString("ascii", 0, 4) === "RIFF" && buf.toString("ascii", 8, 12) === "WEBP") return "image/webp";
  return null;
}
